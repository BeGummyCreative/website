// A video or post the work appears in; `href` is omitted for work not yet published.
export type ProjectLink = {
  label: string;
  href?: string;
};

// A titled block of a project (used for experience write-ups like the TikTok
// internship): optional B2C/B2B-style group label, images, and video links.
export type ProjectSection = {
  group?: string;
  title: string;
  text?: string;
  images?: string[];
  // Links shown directly under a specific image, keyed by that image's path.
  imageLinks?: Record<string, ProjectLink>;
  links?: ProjectLink[];
};

export type PortfolioProject = {
  slug: string;
  title: string;
  category: PortfolioCategory;
  year: string;
  cover: string;
  summary: string;
  description: string[];
  images: string[];
  sections?: ProjectSection[];
  // "logo": the cover is a logo shown whole on the page colour inside a purple frame.
  coverStyle?: "logo";
  // A white-on-transparent logo cover, flipped to black in light mode.
  coverInvertsInLight?: boolean;
  // Alternative cover shown in light mode (e.g. a logo on white instead of black).
  coverLight?: string;
  // Crops the cover to fill the tall Selected Work card, centred on this CSS object-position.
  featureFocus?: string;
  // Per-image size in the gallery collage, keyed by image path: "small" shrinks an image
  // within its column; "large" lifts it into a row across the top of the gallery.
  gallerySizes?: Record<string, "small" | "large">;
  externalUrl?: string;
  externalLabel?: string;
};

